#!/usr/bin/env node
/**
 * Regenerate the emoji name tables the pickers show on hover (desktop) and long press (mobile).
 *
 * Names are the Unicode CLDR short names — the same names the operating systems use for emoji
 * search and screen readers — taken from `emojibase-data`, which publishes CLDR as JSON per locale.
 * The package is not a dependency: it is read once from the npm CDN at a pinned version, and only
 * the emojis the pickers actually offer are written out. That keeps ~1,900 unused entries per
 * locale out of both bundles, and the output is committed, so nothing is fetched at run time.
 *
 * The emoji list is the union of both apps' curations, and each app's own coverage test fails when
 * a curated emoji has no name in a locale. The data's licences are in THIRD_PARTY_NOTICES.md.
 *
 * Usage:
 *   yarn generate:emoji-names
 *
 * Run it after adding emojis to the curated sets, or to move to a newer CLDR release (bump
 * EMOJIBASE_VERSION).
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const EMOJIBASE_VERSION = '18.0.0';
const LOCALES = ['ko', 'en'];
// Both apps keep their own copy of the curation. Reading both means an emoji added to only one of
// them still gets a name, rather than failing that app's coverage test with no way to fix it here.
const CURATIONS = [
    'apps/desktop-web/src/app/features/chat/utils/emoji.ts',
    'apps/web/src/app/features/channels/utils/emoji.ts',
].map(file => path.join(ROOT, file));

/**
 * U+FE0F (emoji presentation selector) is optional in how an emoji is typed: the curation writes
 * `☹️` with it and some keyboards send `☹` without. Keys drop it so either spelling finds the name.
 * Both apps strip it the same way at lookup time.
 */
const nameKey = emoji => emoji.replace(/\uFE0F/g, '');

const readCuratedEmojis = () => {
    const quoted = CURATIONS.flatMap(file =>
        [...fs.readFileSync(file, 'utf-8').matchAll(/'([^'\n]+)'/g)].map(match => match[1])
    );
    // Category keys (`'smileys'`) are quoted too; only pictographic strings are emojis.
    return [...new Set(quoted.filter(value => /\p{Extended_Pictographic}/u.test(value)))];
};

const fetchLabels = async locale => {
    const url = `https://cdn.jsdelivr.net/npm/emojibase-data@${EMOJIBASE_VERSION}/${locale}/compact.json`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const labels = new Map();
    for (const entry of await response.json()) {
        if (entry.unicode && entry.label) labels.set(nameKey(entry.unicode), entry.label);
    }
    return labels;
};

const writeOutputs = (locale, table) => {
    const json = `${JSON.stringify(table, null, 4)}\n`;
    const webFile = path.join(ROOT, `apps/web/public/locales/${locale}/emoji.json`);
    fs.writeFileSync(webFile, json);

    // desktop-web bundles its locales as TS modules rather than fetching JSON.
    const desktopFile = path.join(ROOT, `apps/desktop-web/src/locales/emoji/${locale}.ts`);
    fs.mkdirSync(path.dirname(desktopFile), { recursive: true });
    fs.writeFileSync(
        desktopFile,
        [
            `// Generated by scripts/generate-emoji-names.js (yarn generate:emoji-names). Do not edit.`,
            `// Emoji names from Unicode CLDR via emojibase-data@${EMOJIBASE_VERSION}. CLDR data © Unicode, Inc.,`,
            '// Unicode License v3; emojibase-data © 2017-2019 Miles Johnson, MIT. See THIRD_PARTY_NOTICES.md.',
            `export const emojiNames: Record<string, string> = ${JSON.stringify(table, null, 4)};`,
            '',
        ].join('\n')
    );
    return [webFile, desktopFile];
};

const main = async () => {
    const emojis = readCuratedEmojis();
    const written = [];
    for (const locale of LOCALES) {
        const labels = await fetchLabels(locale);
        const table = {};
        const missing = [];
        for (const emoji of emojis) {
            const label = labels.get(nameKey(emoji));
            if (label) table[nameKey(emoji)] = label;
            else missing.push(emoji);
        }
        if (missing.length > 0) throw new Error(`${locale}: no CLDR name for ${missing.join(' ')}`);
        written.push(...writeOutputs(locale, table));
        console.log(`${locale}: ${Object.keys(table).length} names`);
    }
    execFileSync('npx', ['prettier', '--write', ...written], { cwd: ROOT, stdio: 'inherit' });
};

main().catch(error => {
    console.error(error.message);
    process.exit(1);
});
