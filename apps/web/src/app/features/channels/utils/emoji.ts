/**
 * The key an emoji's name is stored under in the `emoji` i18n namespace.
 *
 * U+FE0F (the emoji presentation selector) is optional in how an emoji is typed — the curation
 * writes `☹️` with it, some keyboards send `☹` without — so the name tables are keyed without it
 * and every lookup strips it the same way. The tables are generated by
 * `scripts/generate-emoji-names.js`, which applies the identical rule.
 */
export const emojiNameKey = (emoji: string): string => emoji.replace(/\uFE0F/g, '');
